export type MsKey = keyof typeof MS;
/** a catalogue string with its `{vars}` filled */
export function mf(key: MsKey, vars: Record<string, string | number | undefined> = {}): string {
  return MS[key].replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] === undefined ? `{${k}}` : String(vars[k])));
}
export const hasKey = (k: string): k is MsKey => Object.hasOwn(MS, k);
