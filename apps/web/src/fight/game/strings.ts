export type FgKey = keyof typeof FG;

/** translate a fight-game key, filling `{name}` placeholders */
export function ft(key: FgKey, vars?: Record<string, string | number>): string {
  let s: string = FG[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export const actionKey = (a: BoxingAction | "guard" | (string & {})): FgKey => (`action.${a}` in FG ? `action.${a}` : "action.jab") as FgKey;
export const decisionKey = (d: BoxingDecision | string): FgKey => (`result.by.${d}` in FG ? `result.by.${d}` : "result.by.points") as FgKey;
/** fouls, including the ones the scoring rules add (read defensively: unknown fouls get the generic text) */
const FOUL_KEYS: Record<string, FgKey> = {
  PASSIVITY: "hud.warnPassivity",
  IDLE: "hud.warnIdle",
  HOLDING: "hud.warnHolding",
  HIT_ON_BREAK: "hud.warnHitOnBreak",
  DUCKING: "hud.warnDucking",
  LOW_BLOW: "hud.warnLowBlow",
};
export const foulKey = (f: Foul | string): FgKey => FOUL_KEYS[f] ?? "hud.warnFoul";
/** the result method (scoring rules) or the older decision, whichever the outcome carries */
export const methodKey = (m: string | undefined, d: BoxingDecision | string): FgKey => {
  const k = `result.by.${m ?? d}`;
  return (k in FG ? k : `result.by.${d}` in FG ? `result.by.${d}` : "result.by.points") as FgKey;
};
