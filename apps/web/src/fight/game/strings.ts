export type FgKey = keyof typeof FG;

/** translate a fight-game key, filling `{name}` placeholders */
export function ft(key: FgKey, vars?: Record<string, string | number>): string {
  let s: string = FG[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export const actionKey = (a: BoxingAction | "guard"): FgKey => `action.${a}` as FgKey;
export const decisionKey = (d: BoxingDecision): FgKey => `result.by.${d}` as FgKey;
export const foulKey = (f: Foul): FgKey => (f === "PASSIVITY" ? "hud.warnPassivity" : "hud.warnIdle");
